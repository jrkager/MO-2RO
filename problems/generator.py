"""The instance generator shared by the selection and the assignment problem.

Both application problems are generated by exactly this routine; they differ only
in how many weight entries an instance has (``n`` items for the selection
problem, ``n*n`` edges for the assignment problem) and in how those entries are
interpreted. Keeping the draw in one place is what makes the claim of
Section "Instance generation" of the paper -- that both problems use the same
instance generator -- true at the level of the code, and it is what stopped
holding when the selection generator was rewritten on its own (commit 2a6c3b9).

The scheme (see the paper for the write-up):

* Two integer first-stage weight vectors ``C`` (objective 1) and ``D``
  (objective 2), shared by all scenarios. Entries are drawn independently from a
  normal distribution with mean 60 and standard deviation 20, truncated to
  [20, 100] and rounded.
* Per scenario ``s`` a multiplier ``m_s``, drawn from a normal distribution with
  mean 1 and standard deviation 0.1, truncated to [0.8, 1.2].
* The second-stage weights are a perturbed copy of the first-stage ones:
  ``c^s_i = max(0, round(m_s * C_i + 20 * xi))`` and likewise for ``d^s`` from
  ``D``, with independent standard normal ``xi`` per entry, objective and
  scenario. The two stages are therefore correlated, while the noise still lets
  them disagree on individual entries.

Random streams. Independent PCG64 streams are derived from the instance
seed: ``[seed, 0]`` for the first-stage weights (drawn entry by entry, row-major
over the four columns), ``[seed, 1]`` for the multipliers (drawn scenario by
scenario), and ``[seed, 2, s]`` for the perturbations of scenario ``s`` (again
entry by entry). Consequently, for a fixed seed:

* the weight vectors of an instance with fewer entries are prefixes of those of
  an instance with more entries, in both stages and in every scenario, and
* the scenarios of an instance are contained unchanged in the otherwise
  identical instance with a larger number of scenarios.

Note that for the assignment problem the entries are the ``n*n`` edges in
row-major order, so this prefix property holds for the flat weight vectors; it
does *not* make the instance on ``n`` vertices per side the sub-instance induced
by the first ``n`` jobs and servers of a larger one, because the flat index
``i*n + j`` of an edge ``(i, j)`` shifts with ``n``. This matches the behaviour
of the previous generator and is the property the paper states.

Do not change the draws or the stream keys without re-running the experiments:
the published runs (e.g. SEL ``run_20260913_231058_new_default``) are
reproducible from this file alone.
"""

import numpy as np
from scipy.stats import truncnorm

# Weight distribution: N(60, 20^2) truncated to [20, 100].
_W_DIST = truncnorm((20 - 60) / 20, (100 - 60) / 20, loc=60, scale=20)
# Scenario multiplier: N(1.0, 0.1^2) truncated to [0.8, 1.2].
_MULT_DIST = truncnorm((0.8 - 1.0) / 0.1, (1.2 - 1.0) / 0.1, loc=1.0, scale=0.1)

# Standard deviation of the additive noise on the second-stage weights.
_NOISE_SD = 20


def generate_weights(entries: int, n_scenarios: int, seed):
    """Draw one instance.

    :param entries: number of weight entries (``n`` items, or ``n*n`` edges)
    :param n_scenarios: number of scenarios to generate
    :param seed: instance seed; ``None`` draws from fresh entropy
    :return: ``(fs_weights_1, fs_weights_2, per_scenario)`` where
        ``per_scenario[s] = (ss_weights_1, ss_weights_2)``; all are lists of
        Python ints, of length ``entries``.
    """
    # Nominal instance: one stream, row-major -> prefix in entries.
    # Four columns are drawn although only the first two are used, so that the
    # stream stays aligned with the published runs.
    u_nom = np.random.default_rng([seed, 0]).random((entries, 4))
    w = _W_DIST.ppf(u_nom).round().astype(int)
    fs1, fs2 = w[:, 0], w[:, 1]

    # Multipliers: one stream over s -> prefix in n_scenarios.
    mult = _MULT_DIST.ppf(np.random.default_rng([seed, 1]).random(n_scenarios))

    per_scenario = []
    for s in range(n_scenarios):
        # Own stream per scenario -> prefix in entries, independent of n_scenarios.
        noise = np.random.default_rng([seed, 2, s]).standard_normal((entries, 2))
        ss1 = np.maximum(0, np.rint(fs1 * mult[s] + _NOISE_SD * noise[:, 0])).astype(int)
        ss2 = np.maximum(0, np.rint(fs2 * mult[s] + _NOISE_SD * noise[:, 1])).astype(int)
        per_scenario.append((ss1.tolist(), ss2.tolist()))

    return fs1.tolist(), fs2.tolist(), per_scenario
